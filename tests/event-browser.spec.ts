import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
test("populated timeline supports filters, keyboard, drag, dialogs and shareable routes", async ({ page }) => {
  await page.goto("/");
  const track = page.getByRole("region", { name: /^Event timeline/ });
  const points = track.getByRole("button");
  await expect(points).toHaveCount(3);
  await points.first().focus(); await page.keyboard.press("ArrowRight"); await expect(points.nth(1)).toBeFocused();
  await page.keyboard.press("End"); await expect(points.last()).toBeFocused();
  await page.keyboard.press("Home"); await expect(points.first()).toBeFocused();
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog"); await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("heading", { name: "Fixture event 1" })).toBeVisible();
  await expect(dialog.getByRole("link", { name: /^Register/ })).toHaveAttribute("href", "https://example.com/register");
  await dialog.click({ position: { x: 10, y: 10 } }); await expect(dialog).toBeVisible();
  await page.keyboard.press("Tab"); expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.keyboard.press("Escape"); await expect(points.first()).toBeFocused();
  await page.getByRole("button", { name: "Hosted by us", exact: true }).click(); await expect(points).toHaveCount(10);
  const bounds = await track.boundingBox(); if (!bounds) throw new Error("Missing timeline bounds");
  await page.mouse.move(bounds.x + bounds.width - 60, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + 70, bounds.y + bounds.height / 2, { steps: 12 }); await page.mouse.up();
  expect(await track.evaluate(element => element.scrollLeft)).toBeGreaterThan(100); await expect(dialog).not.toBeVisible();
  await points.last().focus(); await page.keyboard.press("Enter"); await expect(dialog).toBeVisible();
  await expect(dialog.getByText("Past event", { exact: true })).toBeVisible(); await expect(dialog.getByRole("link", { name: /^Register/ })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "With the community", exact: true }).click(); await expect(points).toHaveCount(1);
  await points.first().click(); await expect(dialog.getByText("Community partner", { exact: true })).toBeVisible();
  await dialog.getByRole("link", { name: /Open shareable event page/ }).click();
  await expect(page).toHaveURL(/\/events\/fixture-event-3$/); await expect(page.locator("h1")).toHaveText("Fixture event 3");
  await page.getByRole("button", { name: "Open Krafty, the duck guide" }).click();
  await expect(page.getByRole("link", { name: "Back to the Krowd Map", exact: true })).toBeVisible();
});
test("event content is server rendered and unknown slugs return 404", async ({ browser, page }) => {
  const context = await browser.newContext({ javaScriptEnabled: false }); const noJS = await context.newPage();
  await noJS.goto("http://127.0.0.1:3180/events/fixture-event-1"); await expect(noJS.locator("h1")).toHaveText("Fixture event 1");
  await expect(noJS.getByText("Fixture venue, Bengaluru")).toBeVisible(); await context.close();
  const response = await page.goto("/events/not-an-event"); expect(response?.status()).toBe(404);
});
